package Collection;

import java.util.*;

public class Try{

    public static void main(String []args){
            int n = 5;
            int size = 2*n-1;

        for (int i = 1; i <= n ; i++) {

            for (int j = 1; j <= size ; j++) {
                System.out.print(i);
            }

            System.out.println();
        }

    }
}